/**
 * Shared by the three implementations the benches compare (raw.ts, statements.ts, session.ts):
 * the tables, the connection, and the seed data. Each implementation exports the same journeys.
 */
import { PgClient } from "@effect/sql-pg";
import { Effect, Layer, ManagedRuntime, Redacted, Schema } from "effect";
import { Model } from "effect/schema";
import { SqlClient } from "effect/sql/SqlClient";
import { DbContext, entity } from "../src/index.ts";

const url = process.env.LINQ_TEST_DATABASE_URL ?? "postgres://postgres:linq@localhost:54871/linq";

export const ROWS = 20_000;

export class Item extends Model.Class<Item>("Item")({
  id: Model.GeneratedByDb(Schema.Number),
  ownerId: Schema.Number,
  name: Schema.String,
  price: Schema.NumberFromString,
  active: Schema.Boolean,
  createdAt: Model.GeneratedByDb(Schema.DateTimeUtcFromDate),
}) {}

export class BenchDb extends DbContext.Service<BenchDb>()(
  "perf/BenchDb",
  { items: entity(Item, (e) => e.toTable("p_items")) },
  { schema: "linq_bench", naming: "snake_case" },
) {}

const runtime = ManagedRuntime.make(
  Layer.provideMerge(BenchDb.layer, PgClient.layer({ url: Redacted.make(url), maxConnections: 2 })),
);

/** The context, as application code gets it from the service. */
export const db = await runtime.runPromise(
  Effect.gen(function* () {
    return yield* BenchDb;
  }),
);

export const run = <A>(effect: Effect.Effect<A, unknown, SqlClient>): Promise<A> =>
  runtime.runPromise(effect);

/** How many times each journey repeats per measured run, so that a run is tens of milliseconds. */
export const REPEAT = { read1000: 30, read10000: 4, edit100: 5, insert1000: 4 } as const;

export const repeat = <A>(
  times: number,
  effect: (iteration: number) => Effect.Effect<A, unknown, SqlClient>,
): Promise<number> =>
  run(
    Effect.gen(function* () {
      for (let i = 0; i < times; i++) yield* effect(i);
      return times;
    }),
  );

/** The price a row is edited to: different for every row and every call. */
export const nextPrice = (price: number, id: number): number => (price * 7 + id) % 1000;

export const newItem = (i: number) => ({
  ownerId: i % 100,
  name: `new ${i}`,
  price: i / 10,
  active: true,
});

/** Creates and fills the table once; every implementation calls it, the first one does the work. */
export const prepare = (): Promise<number> =>
  run(
    Effect.gen(function* () {
      const sql = yield* SqlClient;
      yield* sql.unsafe("select pg_advisory_lock(7411)");
      yield* sql.unsafe("create schema if not exists linq_bench");
      yield* sql.unsafe(
        `create table if not exists linq_bench.p_items (id int generated by default as identity primary key, owner_id int not null, name text not null, price numeric(10,2) not null, active boolean not null, created_at timestamptz not null default now())`,
      );
      yield* sql.unsafe(`delete from linq_bench.p_items where id > ${ROWS}`);
      const [{ count }] = (yield* sql.unsafe(
        "select count(*)::int as count from linq_bench.p_items",
      )) as [{ count: number }];
      if (count !== ROWS) {
        yield* sql.unsafe("truncate linq_bench.p_items restart identity");
        yield* sql.unsafe(
          `insert into linq_bench.p_items (owner_id, name, price, active, created_at) select 1 + g % 100, 'item ' || g, (g % 1000) / 10.0, g % 3 = 0, now() - (g || ' minutes')::interval from generate_series(1, ${ROWS}) g`,
        );
        yield* sql.unsafe("analyze linq_bench.p_items");
      }
      yield* sql.unsafe("select pg_advisory_unlock(7411)");
      return ROWS;
    }),
  );

export const cleanup = db.items.where((i) => i.id > ROWS).executeDelete();
