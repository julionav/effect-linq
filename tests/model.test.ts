const directory = new URL("./.migrations", import.meta.url).pathname;

const Live = Layer.mergeAll(
  PgClient.layer({ url: Redacted.make(DATABASE_URL) }),
  NodeServices.layer,
);

const run = <A, E>(
  effect: Effect.Effect<A, E, any> | { toArray(): Effect.Effect<A, E, any> },
): Promise<A> =>
  Effect.runPromise(
    ("toArray" in effect ? effect.toArray() : effect).pipe(Effect.provide(Live)) as Effect.Effect<
      A,
      E
    >,
  );

const failure = async (effect: Effect.Effect<unknown, unknown, any>): Promise<unknown> => {
  const exit = await Effect.runPromiseExit(
    effect.pipe(Effect.provide(Live)) as Effect.Effect<unknown, unknown>,
  );
  if (!Exit.isFailure(exit)) throw new Error("expected a failure");
  return Cause.squash(exit.cause);
};

const migrate = PgMigrator.run({ loader: fromFileSystem(directory), table: "m_migrations" });

const columnsOf = (table: string) =>
  SqlClient.use((sql) =>
    Effect.map(
      sql.unsafe(
        `select column_name as name, data_type as type, is_nullable as nullable, column_default as "default" from information_schema.columns where table_schema = 'public' and table_name = $1 order by ordinal_position`,
        [table],
      ).values,
      (rows) => rows.map((row) => row.join(" | ")),
    ),
  );

let first: Migrations.Added;

beforeAll(async () => {
  rmSync(directory, { recursive: true, force: true });
  await run(
    SqlClient.use((sql) =>
      sql.unsafe(
        "drop table if exists m_audit, m_taggings, m_articles, m_members, m_migrations cascade",
      ),
    ),
  );
  first = await run(Migrations.add({ context: db, directory, name: "initial" }));
  await run(migrate);
  await run(
    Effect.gen(function* () {
      yield* db.members.insert([
        { email: "ada@example.com", displayName: "Ada", age: 36, balance: 100 },
        { email: "grace@example.com", displayName: "Grace", age: null, balance: 5 },
      ]);
      yield* db.articles.insert([
        {
          authorId: 1 as MemberId,
          reviewerId: 2 as MemberId,
          title: "Engine",
          tags: ["math"],
          meta: { featured: true },
          views: 150n,
        },
        {
          authorId: 1 as MemberId,
          reviewerId: null,
          title: "Numbers",
          tags: [],
          meta: null,
          views: 20n,
        },
        {
          authorId: 2 as MemberId,
          reviewerId: null,
          title: "COBOL",
          tags: ["cobol"],
          meta: null,
          views: 300n,
        },
      ]);
      yield* db.taggings.insert([
        { articleId: 1, tag: "math", weight: 0.5 },
        { articleId: 1, tag: "history", weight: 1 },
      ]);
    }),
  );
});

describe("migrations from the model, run by PgMigrator", () => {
  test("the first migration creates the schema the model describes", async () => {
    expect(first.file).toMatch(/0001_initial\.ts$/);
    const source = readFileSync(first.file!, "utf8");
    expect(source).toContain('import { SqlClient } from "effect/sql/SqlClient";');
    expect(first.statements).toMatchInlineSnapshot(`
      [
        "CREATE TABLE "m_members" (
        "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        "email" text NOT NULL,
        "display_name" text NOT NULL,
        "age" integer,
        "balance" numeric(12,2) DEFAULT 0 NOT NULL,
        "version" integer DEFAULT 1 NOT NULL,
        "created_at" timestamptz NOT NULL,
        "updated_at" timestamptz NOT NULL,
        PRIMARY KEY ("id")
      )",
        "CREATE TABLE "m_articles" (
        "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
        "author_id" integer NOT NULL,
        "reviewer_id" integer,
        "title" text NOT NULL,
        "tags" text[] NOT NULL,
        "meta" jsonb,
        "views" bigint NOT NULL,
        "created_at" timestamptz NOT NULL,
        PRIMARY KEY ("id")
      )",
        "CREATE TABLE "m_taggings" (
        "article_id" integer NOT NULL,
        "tag" text NOT NULL,
        "weight" double precision NOT NULL,
        PRIMARY KEY ("article_id", "tag")
      )",
        "CREATE UNIQUE INDEX "m_members_email_key" ON "m_members" ("email")",
        "CREATE INDEX "m_articles_author_id_created_at_idx" ON "m_articles" ("author_id", "created_at")",
        "ALTER TABLE "m_articles" ADD CONSTRAINT "m_articles_author_id_fkey" FOREIGN KEY ("author_id") REFERENCES "m_members" ("id") ON DELETE CASCADE",
        "ALTER TABLE "m_articles" ADD CONSTRAINT "m_articles_reviewer_id_fkey" FOREIGN KEY ("reviewer_id") REFERENCES "m_members" ("id") ON DELETE SET NULL",
        "ALTER TABLE "m_taggings" ADD CONSTRAINT "m_taggings_article_id_fkey" FOREIGN KEY ("article_id") REFERENCES "m_articles" ("id") ON DELETE CASCADE",
      ]
    `);
    expect(first.warnings).toEqual([]);
    expect(existsSync(`${directory}/snapshot.json`)).toBe(true);
    // PgMigrator recorded it, and running again does nothing
    expect(await run(migrate)).toEqual([]);
    // nothing changed: no new migration
    expect(
      (await run(Migrations.add({ context: db, directory, name: "noop" }))).file,
    ).toBeUndefined();
  });

  test("a changed model becomes the next migration, and only that one runs", async () => {
    const second = await run(
      Migrations.add({ context: dbV2, directory, name: "nicknames_and_audit" }),
    );
    expect(second.file).toMatch(/0002_nicknames_and_audit\.ts$/);
    expect(second.statements).toEqual([
      'CREATE TABLE "m_audit" (\n  "id" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "member_id" integer NOT NULL,\n  "action" text NOT NULL,\n  "at" timestamptz DEFAULT now() NOT NULL,\n  PRIMARY KEY ("id")\n)',
      'ALTER TABLE "m_members" ALTER COLUMN "balance" TYPE numeric(14,2) USING "balance"::numeric(14,2)',
      'ALTER TABLE "m_members" ADD COLUMN "nickname" text',
      'CREATE INDEX "m_members_nickname_idx" ON "m_members" ("nickname")',
      'ALTER TABLE "m_audit" ADD CONSTRAINT "m_audit_member_id_fkey" FOREIGN KEY ("member_id") REFERENCES "m_members" ("id")',
    ]);
    expect(second.warnings).toEqual([
      "m_members.balance changes type from numeric(12,2) to numeric(14,2)",
    ]);
    expect(await run(migrate)).toEqual([[2, "nicknames_and_audit"]]);
    expect(await run(columnsOf("m_members"))).toContain("nickname | text | YES | ");
    // the data survived, and the new context reads the new column
    const rows = await run(
      dbV2.members.orderBy((m) => m.id).select((m) => [m.displayName, m.nickname, m.balance]),
    );
    expect(rows).toEqual([
      ["Ada", null, 100],
      ["Grace", null, 5],
    ]);
    await run(dbV2.audit.insert({ memberId: 1 as MemberId, action: "login", at: new Date() }));
    expect(await run(dbV2.audit.select((a) => a.member.displayName))).toEqual(["Ada"]);
  });

  test("destructive changes are generated with warnings", () => {
    const removed = Migrations.diff(Migrations.snapshot(dbV2), Migrations.snapshot(db));
    const dropKey = removed.statements.indexOf(
      'ALTER TABLE "m_audit" DROP CONSTRAINT "m_audit_member_id_fkey"',
    );
    expect(dropKey).toBeGreaterThanOrEqual(0);
    expect(dropKey).toBeLessThan(removed.statements.indexOf('DROP TABLE "m_audit"'));
    expect(removed.statements).toContain('DROP TABLE "m_audit"');
    expect(removed.statements).toContain('ALTER TABLE "m_members" DROP COLUMN "nickname"');
    expect(removed.warnings).toContain("m_audit is dropped, with its data");
    expect(removed.warnings).toContain("m_members.nickname is dropped, with its data");
  });
});

describe("Model.Class entities", () => {
  const byId = db.members.orderBy((m) => m.id);

  test("rows are instances of the model, with the types of its select variant", async () => {
    const [ada] = await run(byId);
    expect(ada).toBeInstanceOf(Member);
    expect(ada!.label).toBe("Ada <ada@example.com>");
    expect(Schema.is(Member)(ada)).toBe(true);
    expect(DateTime.isDateTime(ada!.createdAt)).toBe(true);
    expect(ada).toMatchObject({ id: 1, age: 36, balance: 100, version: 1 });
    expectTypeOf(ada!.id).toEqualTypeOf<MemberId>();
    expectTypeOf(ada!.createdAt).toEqualTypeOf<DateTime.Utc>();
  });

  test("insert takes the insert variant: generated columns are not given, timestamps are filled in", async () => {
    const before = Date.now();
    const row = await run(
      db.members
        .insert({ email: "linus@example.com", displayName: "Linus", age: 30, balance: 1.5 })
        .returning(),
    );
    expect(row).toBeInstanceOf(Member);
    expect(row.id).toBe(3);
    expect(row.version).toBe(1);
    expect(DateTime.toEpochMillis(row.createdAt)).toBeGreaterThanOrEqual(before - 1000);
    // @ts-expect-error id is generated by the database
    db.members.insert({ id: 9, email: "x", displayName: "x", age: null, balance: 0 });
    // @ts-expect-error displayName is required
    db.members.insert({ email: "x", age: null, balance: 0 });
    // the model validates: displayName is a NonEmptyString
    const invalid = await failure(
      db.members.insert({ email: "x", displayName: "", age: null, balance: 0 }),
    );
    expect(Schema.isSchemaError(invalid)).toBe(true);
  });

  test("executeUpdate refreshes what the update variant refreshes, and respects what it omits", async () => {
    const [before] = await run(byId.where((m) => m.id === 1));
    await new Promise((resolve) => setTimeout(resolve, 5));
    const update = db.members.where((m) => m.id === 1).executeUpdate({ age: 37 });
    expect(update.toSql().sql).toContain('SET "age" = $1, "updated_at" = $2');
    await run(update);
    const [after] = await run(byId.where((m) => m.id === 1));
    expect(after!.age).toBe(37);
    expect(DateTime.toEpochMillis(after!.updatedAt)).toBeGreaterThan(
      DateTime.toEpochMillis(before!.updatedAt),
    );
    expect(DateTime.toEpochMillis(after!.createdAt)).toBe(
      DateTime.toEpochMillis(before!.createdAt),
    );
    const error = await failure(
      db.members.where((m) => m.id === 1).executeUpdate({ createdAt: after!.updatedAt } as never),
    );
    expect(error).toBeInstanceOf(LinqError);
    expect((error as Error).message).toContain("update variant");
  });

  test("relations declared by foreign key and by lambda", async () => {
    const rows = await run(
      db.articles
        .orderBy((a) => a.id)
        .select((a) => ({
          title: a.title,
          author: a.author.displayName,
          reviewer: a.reviewer.displayName,
          tags: a.taggings.orderBy((t) => t.tag).select((t) => t.tag),
        })),
    );
    expect(rows).toEqual([
      { title: "Engine", author: "Ada", reviewer: "Grace", tags: ["history", "math"] },
      { title: "Numbers", author: "Ada", reviewer: null, tags: [] },
      { title: "COBOL", author: "Grace", reviewer: null, tags: [] },
    ]);
    expect(
      await run(byId.select((m) => [m.displayName, m.articles.count(), m.popular.count()]).take(2)),
    ).toEqual([
      ["Ada", 2, 1],
      ["Grace", 1, 1],
    ]);
    const [withArticles] = await run(byId.include("articles").take(1));
    expect(withArticles!.articles[0]).toBeInstanceOf(Article);
    expect(withArticles!.articles.map((a) => a.views)).toEqual([150n, 20n]);
  });

  test("sessions: model defaults on add, refreshed columns and the concurrency token on save", async () => {
    const uow = session();
    const other = session();
    await run(
      Effect.gen(function* () {
        const grace = yield* uow.first(db.members.where((m) => m.email === "grace@example.com"));
        const stale = yield* other.first(db.members.where((m) => m.email === "grace@example.com"));
        expect(grace).toBeInstanceOf(Member);
        const updatedAt = grace.updatedAt;
        yield* Effect.sleep(5);
        grace.displayName = "Grace Hopper";
        const added = uow.add(db.articles, {
          authorId: grace.id,
          reviewerId: null,
          title: "Compilers",
          tags: [],
          meta: null,
          views: 0n,
        });
        expect(yield* uow.saveChanges()).toBe(2);
        expect(added).toBeInstanceOf(Article);
        expect(added.id).toBeGreaterThan(3);
        expect(DateTime.isDateTime(added.createdAt)).toBe(true);
        expect(grace.version).toBe(2);
        expect(DateTime.toEpochMillis(grace.updatedAt)).toBeGreaterThan(
          DateTime.toEpochMillis(updatedAt),
        );
        expect(uow.hasChanges()).toBe(false);

        stale.age = 99;
        expect(yield* Effect.flip(other.saveChanges())).toBeInstanceOf(ConcurrencyError);
        uow.remove(added);
        expect(yield* uow.saveChanges()).toBe(1);
      }),
    );
  });
});

describe("the context as a service", () => {
  // installation: the context's layer on top of a client's
  const AppLive = AppDb.layer.pipe(
    Layer.provide(PgClient.layer({ url: Redacted.make(DATABASE_URL) })),
  );

  // an application service that depends on the context, as it would on any other service
  class Directory extends Context.Service<
    Directory,
    {
      readonly authors: Effect.Effect<Array<string>>;
      readonly rename: (id: MemberId, name: string) => Effect.Effect<number>;
    }
  >()("tests/Directory") {
    static readonly layer = Layer.effect(
      Directory,
      Effect.gen(function* () {
        const db = yield* AppDb;
        return Directory.of({
          authors: db.members
            .where((m) => m.articles.some())
            .orderBy((m) => m.id)
            .select((m) => m.displayName)
            .toArray()
            .pipe(Effect.orDie),
          rename: (id, name) =>
            db.members
              .where((m) => m.id === id)
              .executeUpdate({ displayName: name })
              .pipe(Effect.orDie),
        });
      }),
    );
  }

  const inApp = <A, E>(effect: Effect.Effect<A, E, AppDb | Directory>): Promise<A> =>
    Effect.runPromise(
      effect.pipe(Effect.provide(Layer.provideMerge(Directory.layer, AppLive))) as Effect.Effect<
        A,
        E
      >,
    );

  test("queries from the service need nothing but the service", async () => {
    const program = Effect.gen(function* () {
      const db = yield* AppDb;
      const first = yield* db.members.orderBy((m) => m.id).first();
      const count = yield* db.articles.count((a) => a.author.displayName === first.displayName);
      return { first, count };
    });
    // the only requirement is the context: no SqlClient leaks into application code
    expectTypeOf(program).toEqualTypeOf<
      Effect.Effect<
        { first: Effect.Success<typeof program>["first"]; count: number },
        Effect.Error<typeof program>,
        AppDb
      >
    >();
    const { first, count } = await inApp(program);
    expect(first).toBeInstanceOf(Member);
    expect(count).toBe(2);
  });

  test("other services take the context as a dependency", async () => {
    const authors = await inApp(
      Effect.gen(function* () {
        const directory = yield* Directory;
        return yield* directory.authors;
      }),
    );
    expect(authors.slice(0, 2)).toEqual(["Ada", "Grace Hopper"]);
  });

  test("writes, sessions and transactions on the service", async () => {
    const result = await inApp(
      Effect.gen(function* () {
        const db = yield* AppDb;
        const directory = yield* Directory;
        // a transaction that fails undoes statements and session saves alike
        const failed = yield* Effect.exit(
          db.transaction(
            Effect.gen(function* () {
              yield* directory.rename(1 as MemberId, "Renamed");
              const uow = db.session();
              const grace = yield* uow.first(db.members.where((m) => m.id === 2));
              grace.age = 77;
              yield* uow.saveChanges();
              expect(
                yield* db.members.count((m) => m.displayName === "Renamed" || m.age === 77),
              ).toBe(2);
              return yield* Effect.fail("rollback" as const);
            }),
          ),
        );
        expect(Exit.isFailure(failed)).toBe(true);
        const after = yield* db.members.count((m) => m.displayName === "Renamed" || m.age === 77);

        const uow = db.session();
        const ada = yield* uow.first(db.members.where((m) => m.id === 1));
        ada.age = (ada.age ?? 0) + 1;
        const saved = yield* uow.saveChanges();
        const inserted = yield* db.taggings
          .insert({ articleId: 2, tag: "numbers", weight: 2 })
          .returning((t) => t.tag);
        const removed = yield* db.taggings.where((t) => t.tag === "numbers").executeDelete();
        return { after, saved, version: ada.version, inserted, removed };
      }),
    );
    expect(result).toMatchObject({ after: 0, saved: 1, inserted: "numbers", removed: 1 });
    expect(result.version).toBeGreaterThan(1);
  });

  test("shared query functions keep the service's queries free of other requirements", async () => {
    type ArticleRow = RowIn<typeof AppDb.model.articles>;
    const popular = <W, Env>(articles: Query<ArticleRow, W, Env>) =>
      articles.where((a) => a.views >= 100n);
    const newest =
      (n: number) =>
      <W, Env>(articles: Query<ArticleRow, W, Env>) =>
        articles.orderByDescending((a) => a.id).take(n);
    const program = Effect.gen(function* () {
      const app = yield* AppDb;
      // still writable, and still only needing the context
      expect(app.articles.pipe(popular).executeUpdate({ title: "x" }).toSql().sql).toContain(
        "UPDATE",
      );
      return yield* app.articles.pipe(popular, newest(1)).select((a) => a.title);
    });
    expectTypeOf<Effect.Services<typeof program>>().toEqualTypeOf<AppDb>();
    expect(await inApp(program)).toEqual(["COBOL"]);
  });

  test("the model is available without a connection", async () => {
    expect(Migrations.snapshot(AppDb.model)).toEqual(Migrations.snapshot(db));
    // shared expressions are declared against the model and used with the service
    const isAuthor = quote(AppDb.model.members, (m) => m.articles.some());
    const names = await inApp(
      Effect.gen(function* () {
        const app = yield* AppDb;
        return yield* app.members
          .where(isAuthor)
          .orderBy((m) => m.id)
          .select((m) => m.id);
      }),
    );
    expect(names).toEqual([1, 2]);
    expect(AppDb.model.members.where(isAuthor).toSql().sql).toContain("EXISTS");
  });

  test("the layer can be replaced, as any other", async () => {
    // a second database, a test container, or a client with other settings: only the layer changes
    const Other = AppDb.layer.pipe(
      Layer.provide(
        PgClient.layer({ url: Redacted.make(DATABASE_URL), applicationName: "effect-linq-tests" }),
      ),
    );
    const name = await Effect.runPromise(
      Effect.gen(function* () {
        const app = yield* AppDb;
        return yield* app.members
          .orderBy((m) => m.id)
          .select((m) => m.email)
          .first();
      }).pipe(Effect.provide(Other)),
    );
    expect(name).toBe("ada@example.com");
  });
});
