/**
 * Entities declared the Effect way, as `Model.Class`, and configured with the
 * fluent builder. Used by `tests/model.test.ts`.
 */
import { Schema } from "effect";
import { Model } from "effect/schema";
import { DbContext, entity } from "../src/index.ts";
// the context without a service: what `DbContext.Service` builds on, used here
// where a test wants a second model over the same tables
import { dbContext } from "../src/model.ts";

export const MemberId = Schema.Int.pipe(Schema.brand("MemberId"));
export type MemberId = typeof MemberId.Type;

export class Member extends Model.Class<Member>("Member")({
  // generated by the database; in the update variant too, as SqlModel's update needs the key
  id: Model.Field({ select: MemberId, update: MemberId, json: MemberId }),
  email: Schema.String,
  displayName: Schema.NonEmptyString,
  age: Schema.NullOr(Schema.Int),
  balance: Schema.NumberFromString,
  version: Model.GeneratedByDb(Schema.Int),
  createdAt: Model.DateTimeInsertFromDate,
  updatedAt: Model.DateTimeUpdateFromDate,
}) {
  get label(): string {
    return `${this.displayName} <${this.email}>`;
  }
}

export class Article extends Model.Class<Article>("Article")({
  id: Model.GeneratedByDb(Schema.Int),
  authorId: MemberId,
  reviewerId: Schema.NullOr(MemberId),
  title: Schema.String,
  tags: Schema.Array(Schema.String),
  meta: Schema.NullOr(Schema.Struct({ featured: Schema.Boolean })),
  views: Schema.BigInt,
  createdAt: Model.DateTimeInsertFromDate,
}) {}

export class Tagging extends Model.Class<Tagging>("Tagging")({
  articleId: Schema.Int,
  tag: Schema.String,
  weight: Schema.Number,
}) {}

export const members = entity(Member, (e) =>
  e
    .toTable("m_members")
    .hasKey("id")
    .property("balance", (p) => p.hasColumnType("numeric(12,2)").hasDefaultSql("0"))
    .property("version", (p) => p.hasDefaultSql("1").isConcurrencyToken())
    .hasIndex("email", { unique: true })
    .hasMany("articles", () => Article, { foreignKey: "authorId" })
    // a relation that is not a foreign key is a lambda
    .hasMany(
      "popular",
      () => Article,
      (member, article) => article.authorId === member.id && article.views >= 100n,
    ),
);

export const articles = entity(Article, (e) =>
  e
    .toTable("m_articles")
    .hasIndex(["authorId", "createdAt"])
    .hasOne("author", () => Member, { foreignKey: "authorId", onDelete: "cascade" })
    .hasOptional("reviewer", () => Member, { foreignKey: "reviewerId", onDelete: "set null" })
    .hasMany("taggings", () => Tagging, { foreignKey: "articleId" }),
);

export const taggings = entity(Tagging, (e) =>
  e
    .toTable("m_taggings")
    .hasKey("articleId", "tag")
    .hasOne("article", () => Article, { foreignKey: "articleId", onDelete: "cascade" }),
);

export const db = dbContext({ members, articles, taggings }, { naming: "snake_case" });

/** The same context as a service, installed with `AppDb.layer`. */
export class AppDb extends DbContext.Service<AppDb>()(
  "tests/AppDb",
  { members, articles, taggings },
  { naming: "snake_case" },
) {}

// ---- the same model one release later: a column, an index and a table more

export class MemberV2 extends Model.Class<MemberV2>("MemberV2")({
  ...Model.fields(Member),
  nickname: Schema.NullOr(Schema.String),
}) {}

export class AuditEntry extends Model.Class<AuditEntry>("AuditEntry")({
  id: Model.GeneratedByDb(Schema.BigInt),
  memberId: MemberId,
  action: Schema.String,
  at: Schema.Date,
}) {}

export const dbV2 = dbContext(
  {
    members: entity(MemberV2, (e) =>
      e
        .toTable("m_members")
        .property("balance", (p) => p.hasColumnType("numeric(14,2)").hasDefaultSql("0"))
        .property("version", (p) => p.hasDefaultSql("1").isConcurrencyToken())
        .hasIndex("email", { unique: true })
        .hasIndex("nickname"),
    ),
    articles: entity(Article, (e) =>
      e
        .toTable("m_articles")
        .hasIndex(["authorId", "createdAt"])
        .hasOne("author", () => MemberV2, { foreignKey: "authorId", onDelete: "cascade" })
        .hasOptional("reviewer", () => MemberV2, {
          foreignKey: "reviewerId",
          onDelete: "set null",
        }),
    ),
    taggings,
    audit: entity(AuditEntry, (e) =>
      e
        .toTable("m_audit")
        .property("at", (p) => p.hasDefaultSql("now()"))
        .hasOne("member", () => MemberV2, { foreignKey: "memberId" }),
    ),
  },
  { naming: "snake_case" },
);
