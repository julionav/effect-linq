// ---------------------------------------------------------------- builders

type OnDelete = ForeignKeyDdl["onDelete"];

/** Column-level configuration, as in EF Core's `Property(...)`. */
export class PropertyBuilder {
  /** @internal */
  readonly state: {
    name?: string;
    type?: string;
    defaultSql?: string;
    identity?: boolean;
    concurrencyToken?: boolean;
  } = {};

  /** The column's name, when the naming convention does not give it. */
  hasColumnName(name: string): this {
    this.state.name = name;
    return this;
  }

  /** The column's Postgres type, such as `numeric(12,2)` or `uuid`. Used by migrations. */
  hasColumnType(type: string): this {
    this.state.type = type;
    return this;
  }

  /** A default the database computes, such as `now()` or `gen_random_uuid()`. */
  hasDefaultSql(sql: string): this {
    this.state.defaultSql = sql;
    return this;
  }

  /** `GENERATED BY DEFAULT AS IDENTITY`. Inferred for an integer key the database generates. */
  useIdentityColumn(identity = true): this {
    this.state.identity = identity;
    return this;
  }

  /**
   * A number or bigint column checked and incremented by every session save,
   * so that a row someone else changed fails with `ConcurrencyError`.
   */
  isConcurrencyToken(): this {
    this.state.concurrencyToken = true;
    return this;
  }
}

type FieldKey<M extends Model.Any> = keyof M["fields"] & string;

/** A relation given by its foreign key rather than by a lambda; migrations create the constraint. */
export interface ForeignKey<K extends string> {
  /** The column (or columns, for a composite key) holding the other row's key. */
  readonly foreignKey: K | ReadonlyArray<K>;
  /** What the database does with this row when the row it refers to is deleted. */
  readonly onDelete?: OnDelete;
}

interface RelationSpec {
  readonly name: string;
  readonly kind: Relation["kind"];
  readonly target: () => Model.Any;
  readonly on: Quote | ForeignKey<string>;
}

/** A relation as the builder records it in its type: the target model and the kind. */
export interface Rel<T, Kind> {
  readonly target: T;
  readonly kind: Kind;
}

/** Entity-level configuration, as in EF Core's `Entity<T>(e => ...)`. */
export class EntityBuilder<M extends Model.Any, R = {}> {
  /** @internal */
  readonly state: {
    table?: string;
    schema?: string;
    key?: ReadonlyArray<string>;
    properties: Map<string, PropertyBuilder>;
    indexes: Array<{ columns: ReadonlyArray<string>; unique: boolean; name: string | undefined }>;
    relations: Array<RelationSpec>;
  } = { properties: new Map(), indexes: [], relations: [] };

  /** The table's name (and schema). Defaults to the entity's key in the context. */
  toTable(name: string, options?: { readonly schema?: string }): this {
    this.state.table = name;
    if (options?.schema !== undefined) this.state.schema = options.schema;
    return this;
  }

  /** The primary key. Defaults to `id`. */
  hasKey(...keys: ReadonlyArray<FieldKey<M>>): this {
    this.state.key = keys;
    return this;
  }

  /** Configures one column. */
  property(key: FieldKey<M>, configure: (property: PropertyBuilder) => PropertyBuilder): this {
    let builder = this.state.properties.get(key);
    if (builder === undefined) this.state.properties.set(key, (builder = new PropertyBuilder()));
    configure(builder);
    return this;
  }

  /** An index, created by migrations. */
  hasIndex(
    keys: FieldKey<M> | ReadonlyArray<FieldKey<M>>,
    options?: { readonly unique?: boolean; readonly name?: string },
  ): this {
    this.state.indexes.push({
      columns: typeof keys === "string" ? [keys] : keys,
      unique: options?.unique ?? false,
      name: options?.name,
    });
    return this;
  }

  /** A reference that is always present: this row holds the other row's key in a NOT NULL column. */
  hasOne<const N extends string, T extends Model.Any>(
    name: N,
    target: () => T,
    on: ((row: M["Type"], other: T["Type"]) => boolean) | ForeignKey<FieldKey<M>>,
  ): EntityBuilder<M, R & { readonly [K in N]: Rel<T, "one"> }> {
    return this.relation(name, "one", target, on);
  }

  /** A reference that may be absent: a nullable foreign key, or the far side of a 1:1. */
  hasOptional<const N extends string, T extends Model.Any>(
    name: N,
    target: () => T,
    on: ((row: M["Type"], other: T["Type"]) => boolean) | ForeignKey<FieldKey<M>>,
  ): EntityBuilder<M, R & { readonly [K in N]: Rel<T, "optional"> }> {
    return this.relation(name, "optional", target, on);
  }

  /** A collection: the other rows hold this row's key (`foreignKey` names their column). */
  hasMany<const N extends string, T extends Model.Any>(
    name: N,
    target: () => T,
    on: ((row: M["Type"], other: T["Type"]) => boolean) | ForeignKey<FieldKey<T>>,
  ): EntityBuilder<M, R & { readonly [K in N]: Rel<T, "many"> }> {
    return this.relation(name, "many", target, on);
  }

  private relation(
    name: string,
    kind: Relation["kind"],
    target: () => Model.Any,
    on: unknown,
  ): any {
    let spec: RelationSpec["on"];
    if (typeof on === "function") {
      spec =
        ((on as any)[QuoteSymbol] as Quote | undefined) ??
        fail(
          `relation "${name}": the lambda was not compiled to an expression tree. ` +
            "Add the effect-linq plugin to your build, or run Node with --import effect-linq/register",
        );
    } else {
      spec = on as ForeignKey<string>;
    }
    this.state.relations.push({ name, kind, target, on: spec });
    return this;
  }
}

/** An entity of a context: a model and its configuration. See {@link entity}. */
export interface EntityConfig<M extends Model.Any, R> {
  readonly model: M;
  readonly builder: EntityBuilder<M, R>;
}

/** Declares an entity: an Effect `Model.Class`, and how it maps to a table. */
export const entity = <M extends Model.Any, R = {}>(
  model: M,
  configure?: (entity: EntityBuilder<M>) => EntityBuilder<M, R>,
): EntityConfig<M, R> => {
  const builder = new EntityBuilder<M>();
  return { model, builder: (configure?.(builder) ?? builder) as EntityBuilder<M, R> };
};

// ----------------------------------------------------------------- context

type Entities = { readonly [key: string]: EntityConfig<any, any> };

type TablesOf<Es extends Entities> = {
  readonly [K in keyof Es & string]: Es[K] extends EntityConfig<infer M, any>
    ? ModelTable<K, M>
    : never;
};

type KeyOfModel<Es extends Entities, T> = {
  [K in keyof Es & string]: Es[K] extends EntityConfig<infer M, any>
    ? [M] extends [T]
      ? [T] extends [M]
        ? K
        : never
      : never
    : never;
}[keyof Es & string];

type RelationsOf<Es extends Entities> = {
  readonly [K in keyof Es & string]: Es[K] extends EntityConfig<infer M, infer R>
    ? {
        readonly [N in keyof R]: R[N] extends Rel<
          infer T extends Model.Any,
          infer Kind extends Relation["kind"]
        >
          ? RelationDef<M["Type"], ModelTable<KeyOfModel<Es, T>, T>, Kind>
          : never;
      }
    : never;
};

export interface ContextOptions {
  /** The default Postgres schema of the tables. */
  readonly schema?: string;
  /**
   * How property names become table and column names: as they are (the
   * default), `"snake_case"`, or a function. Match the `transformQueryNames`
   * of your `SqlClient` if `SqlModel` repositories share the tables.
   */
  readonly naming?: "snake_case" | ((name: string) => string);
}

/** What a context knows about its tables: used by migrations and `repository`. */
export interface ContextModel {
  readonly tables: ReadonlyArray<AnyTable>;
  readonly tableOf: (model: Model.Any) => AnyTable;
}

/** One query per entity, as `database` gives, plus the model they were built from. */
export type DbContext<Es extends Entities> = Database<TablesOf<Es>, RelationsOf<Es>> & {
  readonly $model: ContextModel;
};

/** A model's `makeEffect` fails with a schema issue; everything else here fails with `SchemaError`. */
const asSchemaError = <A>(effect: Effect.Effect<A, any>): Effect.Effect<A, Schema.SchemaError> =>
  Effect.mapError(effect, (issue) =>
    Schema.isSchemaError(issue) ? issue : new Schema.SchemaError(issue),
  );

const INT_CHECKS = new Set([
  "effect/schema/isInt",
  "effect/schema/isInt32",
  "effect/schema/isUint32",
  "effect/schema/isUint8",
  "effect/schema/isInt16",
]);

const isInteger = (ast: any): boolean => {
  if (ast?._tag === "Union") return ast.types.some(isInteger);
  const visit = (check: any): boolean =>
    INT_CHECKS.has(check?.annotations?.representation?.id) ||
    (Array.isArray(check?.checks) && check.checks.some(visit));
  return Array.isArray(ast?.checks) && ast.checks.some(visit);
};

const elementAst = (ast: any): any => {
  if (ast?._tag === "Union") {
    return elementAst(ast.types.find((t: any) => t._tag !== "Null" && t._tag !== "Undefined"));
  }
  return ast?._tag === "Arrays" ? ast.rest[0] : undefined;
};

/** The Postgres type a column's schema implies, or undefined when it has to be stated. */
const inferType = (col: Column): string | undefined => {
  const encoded = (Schema.toEncoded(col.schema as any) as Schema.Top).ast;
  const scalar = (wire: string, decoded: string, ast: any): string | undefined => {
    switch (wire) {
      case "string":
        // a number kept exactly: the driver returns numeric as a string
        return decoded === "number" ? "numeric" : "text";
      case "number":
        return isInteger(ast) ? "integer" : "double precision";
      case "bigint":
        return "bigint";
      case "boolean":
        return "boolean";
      case "date":
        return "timestamptz";
      case "bytes":
        return "bytea";
      case "json":
        return "jsonb";
      default:
        return undefined;
    }
  };
  if (col.wire === "array") {
    const element =
      col.element === undefined ? undefined : scalar(col.element, "", elementAst(encoded));
    return element === undefined ? undefined : `${element}[]`;
  }
  return scalar(col.wire, col.type, encoded);
};

const foreignKeyQuote = (
  dependent: ReadonlyArray<string>,
  principal: ReadonlyArray<string>,
  dependentFirst: boolean,
): Quote => {
  // (a, b) => a.fk === b.pk, or (a, b) => b.fk === a.pk for a collection
  const [left, right] = dependentFirst ? ["a", "b"] : ["b", "a"];
  const condition = dependent
    .map((key, i) => ({
      t: "b" as const,
      op: "===" as const,
      l: { t: "m" as const, o: { t: "p" as const, n: left! }, n: key },
      r: { t: "m" as const, o: { t: "p" as const, n: right! }, n: principal[i]! },
    }))
    .reduce((l, r) => ({ t: "b", op: "&&", l, r }) as never);
  return { ast: { v: 1, p: ["a", "b"], b: condition, loc: "foreignKey" }, captures: [] };
};

/**
 * Builds a context: one query per entity, sharing a model. This is the
 * counterpart of EF Core's `DbContext` with its `OnModelCreating`.
 */
export const dbContext = <const Es extends Entities>(
  entities: Es,
  options: ContextOptions = {},
): DbContext<Es> => {
  const naming =
    options.naming === "snake_case" ? snakeCase : (options.naming ?? ((name: string) => name));
  const byModel = new Map<unknown, AnyTable>();
  const tables: Record<string, AnyTable> = {};
  const pending: Array<{
    table: AnyTable;
    config: EntityConfig<any, any>;
    fks: Array<ForeignKeyDdl>;
  }> = [];

  for (const key of Object.keys(entities)) {
    const config = entities[key]!;
    const model = config.model as any;
    const state = config.builder.state;
    const fields: Record<string, Schema.Top> = model.fields;
    const insertFields: Record<string, Schema.Top> = model.insert?.fields ?? fields;
    const updateFields: Record<string, Schema.Top> = model.update?.fields ?? fields;
    const name = state.table ?? naming(key);
    const property = (field: string) => state.properties.get(field)?.state;
    for (const field of state.properties.keys()) {
      if (!(field in fields)) fail(`entity "${key}": "${field}" is not a field of the model`);
    }
    const columnNames: Record<string, string> = {};
    const generated: Array<string> = [];
    let version: string | undefined;
    for (const field of Object.keys(fields)) {
      const p = property(field);
      columnNames[field] = p?.name ?? naming(field);
      if (!(field in insertFields) || p?.defaultSql !== undefined || p?.identity)
        generated.push(field);
      if (p?.concurrencyToken) version = field;
    }
    const base = make(name, model, {
      schema: state.schema ?? options.schema,
      columns: columnNames,
      primaryKey: state.key as never,
      defaults: generated as never,
      version: version as never,
    });

    const onUpdate: Array<ModelInfo["onUpdate"][number]> = [];
    for (const field of Object.keys(updateFields)) {
      const col = base.columns[field];
      if (col === undefined) continue;
      // a field with a constructor default in the update variant is refreshed on every update
      const single = Schema.Struct({ value: updateFields[field]! }) as any;
      const makeValue = Effect.map(asSchemaError(single.makeEffect({})), (made: any) => made.value);
      if (Exit.isSuccess(Effect.runSyncExit(makeValue as Effect.Effect<unknown, unknown>))) {
        onUpdate.push({ col, make: makeValue as never });
      }
    }
    const info: ModelInfo = {
      proto: model.prototype,
      makeInsert: (input) =>
        typeof model.insert?.makeEffect === "function"
          ? asSchemaError(model.insert.makeEffect(input))
          : Effect.succeed(input as Record<string, unknown>),
      onUpdate,
      notUpdatable: new Set(Object.keys(fields).filter((field) => !(field in updateFields))),
    };

    const ddlColumns: Record<string, ColumnDdl> = {};
    for (const col of base.columnList) {
      const p = property(col.key);
      const type = p?.type ?? inferType(col);
      const isKey = base.primaryKey.includes(col);
      const identity =
        p?.identity ??
        (isKey &&
          !(col.key in insertFields) &&
          p?.defaultSql === undefined &&
          (type === "integer" || type === "bigint"));
      Object.defineProperty(ddlColumns, col.key, {
        enumerable: true,
        // only migrations need the type: asked for there, not when the context is built
        get: (): ColumnDdl => ({
          type:
            type ??
            fail(
              `entity "${key}": the Postgres type of "${col.key}" cannot be inferred from its ` +
                `schema; state it with property("${col.key}", (p) => p.hasColumnType("..."))`,
            ),
          defaultSql: p?.defaultSql,
          identity,
        }),
      });
    }
    const indexes: Array<IndexDdl> = state.indexes.map((index) => {
      const columns = index.columns.map(
        (field) =>
          base.columns[field]?.name ?? fail(`entity "${key}": index on unknown field "${field}"`),
      );
      return {
        name: index.name ?? `${name}_${columns.join("_")}_${index.unique ? "key" : "idx"}`,
        columns,
        unique: index.unique,
      };
    });
    const fks: Array<ForeignKeyDdl> = [];
    const table: AnyTable = {
      ...base,
      model: info,
      ddl: { columns: ddlColumns, indexes, foreignKeys: fks },
    };
    if (byModel.has(model)) fail(`dbContext: the model of "${key}" is used by two entities`);
    byModel.set(model, table);
    tables[key] = table;
    pending.push({ table, config, fks });
  }

  const tableOf = (model: unknown, from: string): AnyTable =>
    byModel.get(model) ?? fail(`dbContext: ${from} refers to a model that is not in the context`);

  // relations, now that every table exists
  const rels: Relations = new Map();
  for (const { table, config, fks } of pending) {
    const entries: Record<string, Relation> = {};
    for (const spec of config.builder.state.relations) {
      const where = `relation "${table.name}.${spec.name}"`;
      if (spec.name in table.columns) fail(`${where} collides with a column`);
      const target = tableOf(spec.target(), where);
      let on: Quote;
      if ("ast" in spec.on) {
        on = spec.on;
      } else {
        // the table that holds the foreign key, and the one it points to
        const [dependent, principal] = spec.kind === "many" ? [target, table] : [table, target];
        const keys =
          typeof spec.on.foreignKey === "string" ? [spec.on.foreignKey] : spec.on.foreignKey;
        const columns = keys.map(
          (field) =>
            dependent.columns[field] ??
            fail(`${where}: "${field}" is not a field of "${dependent.name}"`),
        );
        if (principal.primaryKey.length !== columns.length) {
          fail(
            `${where}: the foreign key must have as many columns as the key of "${principal.name}"`,
          );
        }
        on = foreignKeyQuote(
          keys,
          principal.primaryKey.map((col) => col.key),
          spec.kind !== "many",
        );
        const constraint: ForeignKeyDdl = {
          name: `${dependent.name}_${columns.map((col) => col.name).join("_")}_fkey`,
          columns: columns.map((col) => col.name),
          references: () => ({
            table: principal,
            columns: principal.primaryKey.map((col) => col.name),
          }),
          onDelete: spec.on.onDelete ?? "no action",
        };
        // declared from either side, created once
        const list =
          dependent === table ? fks : (dependent.ddl!.foreignKeys as Array<ForeignKeyDdl>);
        const existing = list.findIndex((fk) => fk.name === constraint.name);
        if (existing < 0) list.push(constraint);
        // the side that says what happens on delete wins
        else if (spec.on.onDelete !== undefined) list[existing] = constraint;
      }
      entries[spec.name] = { kind: spec.kind, target, on };
    }
    rels.set(table, entries);
  }

  const out: Record<string, unknown> = {};
  for (const key of Object.keys(tables)) out[key] = new Query(tables[key]!, rels, []);
  const model: ContextModel = {
    tables: Object.values(tables),
    tableOf: (m) => tableOf(m, "tableOf()"),
  };
  Object.defineProperty(out, "$model", { value: model, enumerable: false });
  return out as never;
};

/**
 * An Effect `SqlModel` repository for an entity of the context, with the
 * table name and key taken from its configuration.
 *
 * `SqlModel` writes property names as column names, so with a naming
 * convention the `SqlClient` needs the matching `transformQueryNames` and
 * `transformResultNames`.
 */
export const repository = <T, M extends Model.Any, Name extends string, Env = SqlClient>(
  query: Query<T, ModelTable<Name, M>, Env>,
  options?: { readonly spanPrefix?: string },
): Effect.Effect<
  ReturnType<typeof SqlModel.makeRepository<M, any>> extends Effect.Effect<infer A, any, any>
    ? A
    : never,
  never,
  Env
> => {
  const table = query.table;
  if (table.model === undefined) return fail("repository() needs an entity declared from a Model");
  if (table.primaryKey.length !== 1) {
    return fail(`repository(): "${table.name}" needs a single-column primary key`);
  }
  const name = table.schema === undefined ? table.name : `${table.schema}.${table.name}`;
  // on the query's own client when it came from a context service
  return onClient(
    query.client,
    SqlModel.makeRepository(table.model.proto.constructor as never, {
      tableName: name,
      spanPrefix: options?.spanPrefix ?? table.name,
      idColumn: table.primaryKey[0]!.key as never,
    }),
  ) as never;
};

// ------------------------------------------------------ dependency injection

/**
 * A context as a service hands it out: bound to the `SqlClient` its layer was
 * built with, so that queries and sessions need nothing more to run.
 */
export type BoundContext<Es extends Entities> = Database<TablesOf<Es>, RelationsOf<Es>, never> & {
  /** Starts a unit of work with change tracking, on this context's client. */
  readonly session: () => Session<never>;
  /** Runs effects in one transaction on this context's client. */
  readonly transaction: <A, E, R>(
    effect: Effect.Effect<A, E, R>,
  ) => Effect.Effect<A, E | SqlError, R>;
  readonly $model: ContextModel;
};

const bind = <Es extends Entities>(context: DbContext<Es>, client: SqlClient): BoundContext<Es> => {
  const out: Record<string, unknown> = {};
  for (const key of Object.keys(context)) {
    const query = (context as Record<string, Query<unknown>>)[key]!;
    out[key] = new Query(query.table, query.rels, query.ops, client);
  }
  out.session = () => sessionOn(client);
  out.transaction = (effect: Effect.Effect<unknown, unknown, unknown>) =>
    client.withTransaction(effect);
  Object.defineProperty(out, "$model", { value: context.$model, enumerable: false });
  return out as never;
};

/** The class `DbContext.Service` returns: a service key with its layer and its model. */
export type ContextService<Self, Id extends string, Es extends Entities> = Context.ServiceClass<
  Self,
  Id,
  BoundContext<Es>
> & {
  /**
   * Provides the context, on the `SqlClient` of the environment:
   * `AppDb.layer.pipe(Layer.provide(PgClient.layer(...)))`.
   */
  readonly layer: Layer.Layer<Self, never, SqlClient>;
  /**
   * The context without a client, for what needs the model rather than a
   * connection: migrations, and declaring shared query expressions.
   */
  readonly model: DbContext<Es>;
};

/**
 * The context as a service, installed with a layer: the counterpart of
 * `services.AddDbContext<AppDb>(...)`.
 *
 * ```ts
 * export class AppDb extends DbContext.Service<AppDb>()("app/AppDb", {
 *   users: entity(User, (e) => e.hasMany("posts", () => Post, { foreignKey: "authorId" })),
 *   posts: entity(Post),
 * }, { naming: "snake_case" }) {}
 *
 * const listAdults = Effect.gen(function* () {
 *   const db = yield* AppDb;
 *   return yield* db.users.where((u) => (u.age ?? 0) >= 18);
 * });
 *
 * listAdults.pipe(Effect.provide(AppDb.layer), Effect.provide(PgClient.layer({ url })));
 * ```
 */
export const DbContext = {
  Service:
    <Self>() =>
    <const Id extends string, const Es extends Entities>(
      id: Id,
      entities: Es,
      options?: ContextOptions,
    ): ContextService<Self, Id, Es> => {
      const model = dbContext(entities, options);
      const Base = Context.Service<Self, BoundContext<Es>>()(id) as any;
      const layer = Layer.effect(
        Base,
        SqlClient.use((client) => Effect.succeed(bind(model, client))),
      );
      return Object.assign(Base, { layer, model }) as never;
    },
};
