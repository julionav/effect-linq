/**
 * The model: which `Model.Class` maps to which table, and everything the
 * classes themselves do not say (names, keys, column types, indexes,
 * relations). It is declared once, with a fluent builder per entity, and is
 * what queries, writes, sessions and migrations all read.
 *
 * ```ts
 * export const db = dbContext(
 *   {
 *     users: entity(User, (e) =>
 *       e.hasKey("id").hasIndex("email", { unique: true }).hasMany("posts", () => Post, { foreignKey: "authorId" }),
 *     ),
 *     posts: entity(Post, (e) =>
 *       e.hasOne("author", () => User, { foreignKey: "authorId", onDelete: "cascade" }),
 *     ),
 *   },
 *   { naming: "snake_case" },
 * );
 * ```
 *
 * The classes are ordinary Effect models: the same ones `SqlModel`,
 * `SqlSchema` and `SqlResolver` take.
 */
import { Context, Effect, Exit, Layer, Schema } from "effect";
import type { Model } from "effect/schema";
import { SqlClient } from "effect/sql/SqlClient";
import type { SqlError } from "effect/sql/SqlError";
import * as SqlModel from "effect/sql/SqlModel";
import { fail } from "./errors.ts";
import { type Quote, QuoteSymbol } from "./ir.ts";
import { type Database, onClient, Query, type RelationDef } from "./query.ts";
import { type Session, sessionOn } from "./session.ts";
