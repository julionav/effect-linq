/**
 * Migrations generated from the model, for Effect's `Migrator`.
 *
 * The model is compared with a snapshot of itself from the last time a
 * migration was added; the differences become SQL in a new migration file,
 * and the snapshot is updated. The files are what `PgMigrator.layer` with
 * `fromFileSystem`, `fromGlob` or `fromRecord` runs: this module only writes
 * them, it never runs anything against a database.
 *
 * ```ts
 * // scripts/add-migration.ts, run as:
 * //   node --import @blitz/effect-linq/register scripts/add-migration.ts add_posts
 * await Effect.runPromise(
 *   Migrations.add({ context: db, directory: "migrations", name: process.argv[2]! }).pipe(
 *     Effect.provide(NodeServices.layer),
 *   ),
 * );
 * ```
 */
import { Effect, FileSystem, Path } from "effect";
import { fail } from "./errors.ts";
import type { ContextModel } from "./model.ts";
import type { AnyTable } from "./table.ts";

export interface ColumnSnapshot {
  readonly name: string;
  readonly type: string;
  readonly nullable: boolean;
  readonly default: string | null;
  readonly identity: boolean;
}

export interface TableSnapshot {
  readonly schema: string | null;
  readonly name: string;
  readonly columns: ReadonlyArray<ColumnSnapshot>;
  readonly primaryKey: ReadonlyArray<string>;
  readonly indexes: ReadonlyArray<{
    readonly name: string;
    readonly columns: ReadonlyArray<string>;
    readonly unique: boolean;
  }>;
  readonly foreignKeys: ReadonlyArray<{
    readonly name: string;
    readonly columns: ReadonlyArray<string>;
    readonly references: {
      readonly schema: string | null;
      readonly table: string;
      readonly columns: ReadonlyArray<string>;
    };
    readonly onDelete: string;
  }>;
}

/** The model as migrations see it: plain JSON, kept next to the migration files. */
export interface Snapshot {
  readonly version: 1;
  readonly tables: { readonly [qualifiedName: string]: TableSnapshot };
}

export const empty: Snapshot = { version: 1, tables: {} };

type Context = { readonly $model: ContextModel };

const ident = (name: string): string => `"${name.replaceAll('"', '""')}"`;

const qualified = (table: { readonly schema: string | null | undefined; readonly name: string }) =>
  table.schema == null ? ident(table.name) : `${ident(table.schema)}.${ident(table.name)}`;

const keyOf = (table: { readonly schema: string | null | undefined; readonly name: string }) =>
  table.schema == null ? table.name : `${table.schema}.${table.name}`;

const tableSnapshot = (table: AnyTable): TableSnapshot => {
  const ddl = table.ddl ?? fail(`"${table.name}" was not declared in a dbContext`);
  return {
    schema: table.schema ?? null,
    name: table.name,
    columns: table.columnList.map((col) => {
      const column = ddl.columns[col.key]!;
      return {
        name: col.name,
        type: column.type,
        nullable: col.nullable,
        default: column.defaultSql ?? null,
        identity: column.identity,
      };
    }),
    primaryKey: table.primaryKey.map((col) => col.name),
    indexes: ddl.indexes.map((index) => ({ ...index })),
    foreignKeys: ddl.foreignKeys.map((fk) => {
      const target = fk.references();
      return {
        name: fk.name,
        columns: fk.columns,
        references: {
          schema: target.table.schema ?? null,
          table: target.table.name,
          columns: target.columns,
        },
        onDelete: fk.onDelete,
      };
    }),
  };
};

/** The model of a context, as a snapshot. */
export const snapshot = (context: Context): Snapshot => {
  const tables: Record<string, TableSnapshot> = {};
  for (const table of context.$model.tables) tables[keyOf(table)] = tableSnapshot(table);
  return { version: 1, tables };
};

const columnSql = (column: ColumnSnapshot): string =>
  ident(column.name) +
  " " +
  column.type +
  (column.identity ? " GENERATED BY DEFAULT AS IDENTITY" : "") +
  (column.default === null ? "" : ` DEFAULT ${column.default}`) +
  (column.nullable ? "" : " NOT NULL");

const indexSql = (table: TableSnapshot, index: TableSnapshot["indexes"][number]): string =>
  `CREATE ${index.unique ? "UNIQUE " : ""}INDEX ${ident(index.name)} ON ${qualified(table)} (${index.columns.map(ident).join(", ")})`;

const foreignKeySql = (table: TableSnapshot, fk: TableSnapshot["foreignKeys"][number]): string =>
  `ALTER TABLE ${qualified(table)} ADD CONSTRAINT ${ident(fk.name)} FOREIGN KEY (${fk.columns.map(ident).join(", ")}) ` +
  `REFERENCES ${qualified({ schema: fk.references.schema, name: fk.references.table })} (${fk.references.columns.map(ident).join(", ")})` +
  (fk.onDelete === "no action" ? "" : ` ON DELETE ${fk.onDelete.toUpperCase()}`);

const same = (a: unknown, b: unknown): boolean => JSON.stringify(a) === JSON.stringify(b);

export interface Diff {
  /** SQL statements, in an order that can be run as they are. */
  readonly statements: ReadonlyArray<string>;
  /** Changes that lose data or may fail on existing rows; review them. */
  readonly warnings: ReadonlyArray<string>;
}

/**
 * The statements that take a database from one model to another.
 *
 * A renamed table or column is seen as one dropped and one added: edit the
 * generated migration to `RENAME` instead when the data must be kept.
 */
export const diff = (from: Snapshot, to: Snapshot): Diff => {
  const warnings: Array<string> = [];
  // phases, so that constraints never refer to something not there (yet, or any more)
  const dropConstraints: Array<string> = [];
  const dropTables: Array<string> = [];
  const schemas: Array<string> = [];
  const tables: Array<string> = [];
  const columns: Array<string> = [];
  const indexes: Array<string> = [];
  const constraints: Array<string> = [];

  const knownSchemas = new Set(Object.values(from.tables).map((table) => table.schema));
  for (const [key, next] of Object.entries(to.tables)) {
    const previous = from.tables[key];
    if (next.schema !== null && !knownSchemas.has(next.schema)) {
      knownSchemas.add(next.schema);
      schemas.push(`CREATE SCHEMA IF NOT EXISTS ${ident(next.schema)}`);
    }
    const name = qualified(next);
    if (previous === undefined) {
      const lines = next.columns.map(columnSql);
      if (next.primaryKey.length > 0) {
        lines.push(`PRIMARY KEY (${next.primaryKey.map(ident).join(", ")})`);
      }
      tables.push(`CREATE TABLE ${name} (\n  ${lines.join(",\n  ")}\n)`);
      for (const index of next.indexes) indexes.push(indexSql(next, index));
      for (const fk of next.foreignKeys) constraints.push(foreignKeySql(next, fk));
      continue;
    }

    // columns
    const before = new Map(previous.columns.map((column) => [column.name, column]));
    const after = new Map(next.columns.map((column) => [column.name, column]));
    for (const column of next.columns) {
      const old = before.get(column.name);
      if (old === undefined) {
        columns.push(`ALTER TABLE ${name} ADD COLUMN ${columnSql(column)}`);
        if (!column.nullable && column.default === null && !column.identity) {
          warnings.push(
            `${key}.${column.name} is added NOT NULL without a default: this fails if the table has rows`,
          );
        }
        continue;
      }
      const alter = `ALTER TABLE ${name} ALTER COLUMN ${ident(column.name)}`;
      if (old.type !== column.type) {
        columns.push(`${alter} TYPE ${column.type} USING ${ident(column.name)}::${column.type}`);
        warnings.push(`${key}.${column.name} changes type from ${old.type} to ${column.type}`);
      }
      if (old.default !== column.default) {
        columns.push(
          column.default === null
            ? `${alter} DROP DEFAULT`
            : `${alter} SET DEFAULT ${column.default}`,
        );
      }
      if (old.identity !== column.identity) {
        columns.push(
          column.identity
            ? `${alter} ADD GENERATED BY DEFAULT AS IDENTITY`
            : `${alter} DROP IDENTITY IF EXISTS`,
        );
      }
      if (old.nullable !== column.nullable) {
        columns.push(column.nullable ? `${alter} DROP NOT NULL` : `${alter} SET NOT NULL`);
        if (!column.nullable) {
          warnings.push(`${key}.${column.name} becomes NOT NULL: this fails if it holds nulls`);
        }
      }
    }
    for (const column of previous.columns) {
      if (!after.has(column.name)) {
        columns.push(`ALTER TABLE ${name} DROP COLUMN ${ident(column.name)}`);
        warnings.push(`${key}.${column.name} is dropped, with its data`);
      }
    }
    if (!same(previous.primaryKey, next.primaryKey)) {
      if (previous.primaryKey.length > 0) {
        dropConstraints.push(`ALTER TABLE ${name} DROP CONSTRAINT ${ident(`${next.name}_pkey`)}`);
      }
      if (next.primaryKey.length > 0) {
        columns.push(
          `ALTER TABLE ${name} ADD PRIMARY KEY (${next.primaryKey.map(ident).join(", ")})`,
        );
      }
    }

    // indexes and foreign keys, by name
    const oldIndexes = new Map(previous.indexes.map((index) => [index.name, index]));
    for (const index of next.indexes) {
      const old = oldIndexes.get(index.name);
      oldIndexes.delete(index.name);
      if (old !== undefined && same(old, index)) continue;
      if (old !== undefined)
        dropConstraints.push(`DROP INDEX ${qualified({ schema: next.schema, name: index.name })}`);
      indexes.push(indexSql(next, index));
    }
    for (const index of oldIndexes.values()) {
      dropConstraints.push(`DROP INDEX ${qualified({ schema: next.schema, name: index.name })}`);
    }
    const oldKeys = new Map(previous.foreignKeys.map((fk) => [fk.name, fk]));
    for (const fk of next.foreignKeys) {
      const old = oldKeys.get(fk.name);
      oldKeys.delete(fk.name);
      if (old !== undefined && same(old, fk)) continue;
      if (old !== undefined) {
        dropConstraints.push(`ALTER TABLE ${name} DROP CONSTRAINT ${ident(fk.name)}`);
      }
      constraints.push(foreignKeySql(next, fk));
    }
    for (const fk of oldKeys.values()) {
      dropConstraints.push(`ALTER TABLE ${name} DROP CONSTRAINT ${ident(fk.name)}`);
    }
  }

  for (const [key, previous] of Object.entries(from.tables)) {
    if (to.tables[key] !== undefined) continue;
    for (const fk of previous.foreignKeys) {
      dropConstraints.push(`ALTER TABLE ${qualified(previous)} DROP CONSTRAINT ${ident(fk.name)}`);
    }
    dropTables.push(`DROP TABLE ${qualified(previous)}`);
    warnings.push(`${key} is dropped, with its data`);
  }

  return {
    statements: [
      ...dropConstraints,
      ...dropTables,
      ...schemas,
      ...tables,
      ...columns,
      ...indexes,
      ...constraints,
    ],
    warnings,
  };
};

/** The statements that create everything in the model, for a new database or a test. */
export const createScript = (context: Context): ReadonlyArray<string> =>
  diff(empty, snapshot(context)).statements;

/** The source of a migration file that runs the statements. */
export const render = (
  statements: ReadonlyArray<string>,
  warnings: ReadonlyArray<string> = [],
): string => {
  const literal = (sql: string): string =>
    "`" + sql.replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${") + "`";
  return [
    `// Generated by effect-linq from the model. Review it, and edit it if a change`,
    `// should keep data (a rename is generated as a drop and an add).`,
    ...warnings.map((warning) => `// WARNING: ${warning}`),
    `import { Effect } from "effect";`,
    `import { SqlClient } from "effect/sql/SqlClient";`,
    ``,
    `export default Effect.gen(function* () {`,
    `  const sql = yield* SqlClient;`,
    ...statements.map(
      (statement) => `  yield* sql.unsafe(${literal(statement).replaceAll("\n", "\n  ")});`,
    ),
    `});`,
    ``,
  ].join("\n");
};

export interface AddOptions {
  readonly context: Context;
  /** Where the migration files and `snapshot.json` are kept. */
  readonly directory: string;
  /** A short name, such as `add_posts`. */
  readonly name: string;
}

export interface Added extends Diff {
  /** The file that was written, or undefined when the model has not changed. */
  readonly file: string | undefined;
}

/**
 * Writes the next migration: the difference between the model and the
 * snapshot in `directory`, as `<id>_<name>.ts`, and the new snapshot.
 * Nothing is written when there is no difference.
 */
export const add = (
  options: AddOptions,
): Effect.Effect<Added, unknown, FileSystem.FileSystem | Path.Path> =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    if (!/^[A-Za-z0-9_-]+$/.test(options.name)) {
      return yield* Effect.die(
        new Error(`migration name "${options.name}" must be letters, digits, _ or -`),
      );
    }
    yield* fs.makeDirectory(options.directory, { recursive: true });
    const snapshotFile = path.join(options.directory, "snapshot.json");
    const previous: Snapshot = (yield* fs.exists(snapshotFile))
      ? JSON.parse(yield* fs.readFileString(snapshotFile))
      : empty;
    const next = snapshot(options.context);
    const changes = diff(previous, next);
    if (changes.statements.length === 0) return { ...changes, file: undefined };
    let last = 0;
    for (const file of yield* fs.readDirectory(options.directory)) {
      const match = /^(\d+)_[^.]+\.(js|ts|mjs|mts)$/.exec(file);
      if (match !== null) last = Math.max(last, Number(match[1]));
    }
    const file = path.join(
      options.directory,
      `${String(last + 1).padStart(4, "0")}_${options.name}.ts`,
    );
    yield* fs.writeFileString(file, render(changes.statements, changes.warnings));
    yield* fs.writeFileString(snapshotFile, `${JSON.stringify(next, null, 2)}\n`);
    return { ...changes, file };
  });
